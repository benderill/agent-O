// Static checks on the HTML pages: no absolute links (the site must work from a subpath such as /agent-O/),
// one repository for all GitHub and Colab links, Ax pages that link to files that exist, and credit lines.
// The browser checks (console errors, screenshots, controls) are in scripts/check-site.mjs.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PROBLEMS } from '../src/problems/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = 'benderill/agent-O';
const pages = ['index.html', 'lessons/surrogate-acquisition.html', ...readdirSync(join(root, 'ax')).filter((f) => f.endsWith('.html')).map((f) => `ax/${f}`)];
const read = (p) => readFileSync(join(root, p), 'utf8');
const attrs = (html) => [...html.matchAll(/\s(?:href|src)="([^"]*)"/g)].map((m) => m[1]);

test('pages use relative URLs only, so the site works under a subpath', () => {
  for (const p of pages) {
    for (const url of attrs(read(p))) {
      assert.ok(!url.startsWith('/'), `${p}: absolute path ${url}`);
      assert.ok(!/^https?:\/\/(localhost|127\.)/.test(url), `${p}: local URL ${url}`);
    }
  }
});

test('internal links and assets point to files that exist', () => {
  for (const p of pages) {
    for (const url of attrs(read(p))) {
      if (/^(https?:|data:|mailto:|#|\?)/.test(url) || url === '') continue;
      const target = resolve(join(root, dirname(p)), url.split(/[?#]/)[0]);
      const file = url.endsWith('/') || url === '../' || url === './' ? join(target, 'index.html') : target;
      assert.ok(existsSync(file), `${p}: ${url} does not exist`);
    }
  }
});

test('all GitHub and Colab links use the same repository', () => {
  for (const p of pages) {
    for (const url of attrs(read(p))) {
      const m = /github\.com\/([^/]+\/[^/"#?]+)/.exec(url);
      if (!m || url.includes('github.com/sgbaird') || url.includes('github.com/facebook')) continue;
      assert.equal(m[1], REPO, `${p}: ${url}`);
    }
  }
});

test('every problem with an Ax page has the page, its script, notebook and credits', () => {
  for (const def of PROBLEMS.filter((d) => d.axPage)) {
    const html = read(def.axPage);
    const base = def.axPage.replace(/\.html$/, '');
    for (const ext of ['.py', '.ipynb']) assert.ok(existsSync(join(root, base + ext)), `${base + ext} missing`);
    assert.ok(existsSync(join(root, dirname(def.axPage), 'generated', `${def.id}.honegumi.py`)), 'unedited Honegumi output missing');
    assert.match(html, /colab\.research\.google\.com\/github\/benderill\/agent-O\/blob\/main\/ax\/[\w-]+\.ipynb/);
    assert.match(html, /Honegumi[\s\S]*MIT license[\s\S]*Ax[\s\S]*MIT license/, 'credit line with licenses');
  }
});

test('the Ax script is Honegumi output plus marked edits only', () => {
  const generated = read('ax/generated/dilution.honegumi.py');
  const adapted = read('ax/dilution.py');
  assert.match(generated, /^# Generated by Honegumi/);
  assert.match(adapted, /^# Generated by Honegumi/);
  // Lines of the generated script that are not in the adapted one must have been replaced by MOD lines.
  const kept = new Set(adapted.split('\n'));
  const dropped = generated.split('\n').filter((l) => l.trim() && !kept.has(l));
  assert.ok(dropped.length > 0 && adapted.includes('# MOD:'), 'expected marked edits');
  for (const l of dropped) assert.ok(/branin|x1|x2|range\(19\)|AxClient\(\)|%pip|^\s+(y = float|\(x2|\+ 10|return y|\))/.test(l), `unexpected removal: ${l}`);
});
